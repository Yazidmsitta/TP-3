-- Executer ces requetes pendant une pause de DemoH2Navigateur.
SELECT * FROM REPARATEURS ORDER BY ID;
SELECT * FROM INTERVENTIONS ORDER BY ID;
SELECT * FROM COMPETENCES ORDER BY ID;
SELECT * FROM REPARATEUR_COMPETENCE ORDER BY REPARATEUR_ID, COMPETENCE_ID;

-- Bilan des quatre tables sur une seule ligne.
SELECT
    (SELECT COUNT(*) FROM REPARATEURS) AS REPARATEURS,
    (SELECT COUNT(*) FROM INTERVENTIONS) AS INTERVENTIONS,
    (SELECT COUNT(*) FROM COMPETENCES) AS COMPETENCES,
    (SELECT COUNT(*) FROM REPARATEUR_COMPETENCE) AS LIENS;

-- Fiches avec le nom du reparateur.
SELECT R.NOM AS REPARATEUR, I.OBJET, I.STATUT
FROM REPARATEURS R
JOIN INTERVENTIONS I ON I.REPARATEUR_ID = R.ID
ORDER BY R.NOM, I.OBJET;

-- Competences declarees, dont Electronique partagee au depart.
SELECT R.NOM AS REPARATEUR, C.LIBELLE AS COMPETENCE
FROM REPARATEURS R
JOIN REPARATEUR_COMPETENCE RC ON RC.REPARATEUR_ID = R.ID
JOIN COMPETENCES C ON C.ID = RC.COMPETENCE_ID
ORDER BY R.NOM, C.LIBELLE;
